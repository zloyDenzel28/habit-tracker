"""Коды ошибок для OpenAPI — то, что API давно умеет отдавать, но чего не
было видно в схеме.

FastAPI выводит в спеку только успешный ответ и 422 от валидации Pydantic.
Всё остальное здесь берётся из двух обработчиков в app/api/main.py и из
HTTPException внутри зависимостей — вывести это автоматически неоткуда,
приходится перечислять руками.

Перечисление лежит в одном месте, а не расписано по ручкам: набор кодов
задаёт единая таблица «доменная ошибка → HTTP» в service_error_handler
(инвариант 4 — решение принимает сервисный слой, адаптер только выбирает
код). Если таблица поменяется, править описания надо здесь, а не искать их
по двадцати декораторам.

Словари складываются: `responses={**UNAUTHORIZED, **NOT_FOUND_OCCURRENCE}`.
"""

from __future__ import annotations

from typing import Any

from app.api.schemas import ErrorOut


def _error(description: str) -> dict[str, Any]:
    return {"model": ErrorOut, "description": description}


UNAUTHORIZED = {
    401: _error(
        "Токен не передан, не разобран как UUID или такого пользователя нет. "
        "Получить токен: POST /auth/dev-login"
    )
}

NOT_FOUND_HABIT = {
    404: _error(
        "Привычки с таким id нет — или она есть, но принадлежит другому "
        "пользователю. Оба случая отвечают одинаково, чтобы не подтверждать "
        "существование чужого id"
    )
}

NOT_FOUND_PAUSE = {
    404: _error("Нет такой привычки или у этой привычки нет такой паузы")
}

NOT_FOUND_OCCURRENCE = {
    404: _error("Занятия с таким id нет или оно принадлежит другому пользователю")
}

# §5. Три доменные ошибки сходятся в один код: переход, которого нет в
# таблице статусов; переход в статус, в котором занятие уже стоит; шестой
# снуз подряд. Текст в detail различает их между собой.
CONFLICT_TRANSITION = {
    409: _error(
        "Переход запрещён: занятие в статусе, из которого так нельзя, уже "
        "в целевом статусе или исчерпан лимит снузов (§5)"
    )
}

# Уникальный индекс (habit_id, scheduled_at) — бизнес-правило «одно занятие
# на привычку и время» (инвариант 7). Ловится только на записи: сдвиг
# расписания или таймзоны может свести два будущих занятия в один момент.
CONFLICT_SCHEDULE = {
    409: _error("После пересчёта расписания два занятия сошлись на одном времени")
}

# Единственная ручка без токена, поэтому и коды у неё свои: оба случая
# означают «дев-вход не настроен», а не ошибку вызывающего.
DEV_LOGIN_ERRORS = {
    404: _error("DEV_AUTH выключен или сид-пользователя нет в базе"),
    500: _error("SEED_TELEGRAM_ID не задан в окружении — некого логинить"),
}

VALIDATION = {
    400: _error(
        "Правило предметной области не выполнено: длительность вне допустимых "
        "границ, пустой список дней недели, неизвестная таймзона IANA, пауза "
        "задним числом. Что именно — в detail"
    )
}
